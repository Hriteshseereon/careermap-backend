import {
createCounseling,
getCounselings,
getCounselingById,
updateCounseling,
deleteCounseling,
 generateCounselingReport
} from "./counseling.services.js";
import PDFDocument from "pdfkit";
export const createCounselingController = async (req, res) => {
const result = await createCounseling(req.body);
res.status(result.success ? 201 : 400).json(result);
};

export const getCounselingsController = async (req, res) => {
const result = await getCounselings();
res.status(200).json(result);
};

export const getCounselingByIdController = async (req, res) => {
const result = await getCounselingById(req.params.id);
res.status(result.success ? 200 : 404).json(result);
};

export const updateCounselingController = async (req, res) => {
const result = await updateCounseling(req.params.id, req.body);
res.status(result.success ? 200 : 400).json(result);
};

export const deleteCounselingController = async (req, res) => {
const result = await deleteCounseling(req.params.id);
res.status(result.success ? 200 : 400).json(result);
};

export const downloadCounselingReportController = async (
  req,
  res
) => {
  try {
    const result = await generateCounselingReport(
      req.params.id
    );

    if (!result.success) {
      return res.status(404).json(result);
    }

    const data = result.data;

    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
    });

    const fileName = `Counseling_Report_${data.id}.pdf`;

    res.setHeader(
      "Content-Type",
      "application/pdf"
    );

    res.setHeader(
      "Content-Disposition",
      `attachment; filename=${fileName}`
    );

    doc.pipe(res);

    // =========================
    // HEADER
    // =========================

    doc
      .fontSize(24)
      .fillColor("#1e40af")
      .text("CAREER COUNSELING REPORT", {
        align: "center",
      });

    doc.moveDown(0.5);

    doc
      .fontSize(10)
      .fillColor("gray")
      .text(
        `Generated On: ${new Date().toLocaleDateString()}`,
        {
          align: "right",
        }
      );

    doc.moveDown(2);

    // =========================
    // PERSONAL DETAILS
    // =========================

    doc
      .fontSize(18)
      .fillColor("#111827")
      .text("Personal Information");

    doc.moveDown(0.5);

    doc
      .strokeColor("#d1d5db")
      .lineWidth(1)
      .rect(doc.x, doc.y, 500, 130)
      .stroke();

    let startY = doc.y + 15;

    doc
      .fontSize(12)
      .fillColor("black")
      .text(
        `Full Name : ${data.firstName || ""} ${
          data.lastName || ""
        }`,
        60,
        startY
      )
      .text(
        `Email : ${data.email || "-"}`,
        60,
        startY + 25
      )
      .text(
        `Inquiry For : ${data.inquiryFor || "-"}`,
        60,
        startY + 50
      )
      .text(
        `Study Level : ${data.study || "-"}`,
        60,
        startY + 75
      )
      .text(
        `Interest : ${data.interest || "-"}`,
        60,
        startY + 100
      );

    doc.moveDown(9);

    // =========================
    // DESCRIPTION
    // =========================

    doc
      .fontSize(18)
      .fillColor("#111827")
      .text("Student Description");

    doc.moveDown(0.5);

    doc
      .strokeColor("#d1d5db")
      .rect(doc.x, doc.y, 500, 150)
      .stroke();

    doc.text(
      data.description ||
        "No description provided.",
      60,
      doc.y + 15,
      {
        width: 460,
        align: "justify",
      }
    );

    doc.moveDown(12);

    // =========================
    // RECOMMENDATION
    // =========================

    doc
      .fontSize(18)
      .fillColor("#111827")
      .text("Counselor Notes");

    doc.moveDown();

    doc
      .fontSize(12)
      .fillColor("#374151")
      .text(
        "This report contains the submitted counseling inquiry details. Counselors may review the candidate profile and provide appropriate career guidance, course recommendations, and further consultation."
      );

    // =========================
    // FOOTER
    // =========================

    doc.moveDown(4);

    doc
      .fontSize(10)
      .fillColor("gray")
      .text(
        "Generated by Career Counseling Management System",
        {
          align: "center",
        }
      );

    doc.end();
  } catch (error) {
    console.error(error);

    return res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};